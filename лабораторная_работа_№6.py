import matplotlib.pyplot as plt
import numpy as np

fig, axes = plt.subplots(1, 3, figsize=(18, 5))

languages = ['Python', 'C++', 'Java', 'JS']
popularity = [45, 20, 15, 20]
axes[0].bar(languages, popularity, color=['royalblue', 'tomato', 'gold', 'limegreen'])
axes[0].set_title('1. Столбчатая диаграмма (bar)')
axes[0].set_ylabel('Популярность (%)')
axes[0].grid(axis='y', linestyle='--', alpha=0.7)

axes[1].pie(popularity, labels=languages, autopct='%1.1f%%', startangle=90,
            colors=['lightblue', 'lightcoral', 'khaki', 'lightgreen'])
axes[1].set_title('2. Круговая диаграмма (pie)')

np.random.seed(42)
random_data = np.random.normal(loc=0, scale=1, size=500)
axes[2].hist(random_data, bins=20, color='mediumpurple', edgecolor='black')
axes[2].set_title('3. Гистограмма (hist)')
axes[2].set_xlabel('Значение')
axes[2].set_ylabel('Частота')

plt.tight_layout()
plt.show()

